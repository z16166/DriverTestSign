const wchar_t* Tr(Str id) {
    const unsigned index = static_cast<unsigned>(id);
    if (index >= kCount) {
        return L"";
    }
    const wchar_t* const* table =
        g_language == UiLanguage::ChineseSimplified ? kChinese : kEnglish;
    return table[index];
}

